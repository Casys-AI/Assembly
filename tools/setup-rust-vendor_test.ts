Deno.test("ensureRustVendor refuses and preserves a divergent Cargo configuration", async () => {
  const f = await fixture();
  try {
    const installed = await ensureRustVendor(f.options);
    const changed = "[net]\noffline = false\n";
    await Deno.writeTextFile(installed.cargoConfig, changed);
    await assert.rejects(
      ensureRustVendor(f.options),
      /Refusing divergent Rust vendor cargo config/,
    );
    assert.equal(await Deno.readTextFile(installed.cargoConfig), changed);
  } finally {
    await Deno.remove(f.root, { recursive: true });
  }
});
