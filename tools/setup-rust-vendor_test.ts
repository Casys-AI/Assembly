Deno.test("ensureRustVendor refuses extra files and symlinks in the tree", async () => {
  const f = await fixture();
  try {
    await ensureRustVendor(f.options);
    const extra = `${f.options.vendorDirectory}/demo-1.0.0/extra.txt`;
    await Deno.writeTextFile(extra, "extra");
    await assert.rejects(
      ensureRustVendor(f.options),
      /files differ from the manifest/,
    );
    await Deno.remove(extra);
    await Deno.symlink(
      "/tmp",
      `${f.options.vendorDirectory}/demo-1.0.0/src/link`,
    );
    await assert.rejects(ensureRustVendor(f.options), /symlink refused/);
  } finally {
    await Deno.remove(f.root, { recursive: true });
  }
});

