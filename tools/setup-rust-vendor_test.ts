Deno.test("ensureRustVendor preserves a divergent pre-existing tree", async () => {
  const f = await fixture();
  try {
    await Deno.mkdir(`${f.options.vendorDirectory}/demo-1.0.0`, {
      recursive: true,
    });
    const stray = `${f.options.vendorDirectory}/demo-1.0.0/stray.txt`;
    await Deno.writeTextFile(stray, "keep me");
    await assert.rejects(
      ensureRustVendor(f.options),
      /differ from the manifest/,
    );
    assert.equal(decoder.decode(await Deno.readFile(stray)), "keep me");
  } finally {
    await Deno.remove(f.root, { recursive: true });
  }
});

